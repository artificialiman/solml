// Prints each LiteSVM step so a native crash shows which call caused it.
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { Clock, LiteSVM, TransactionMetadata } from "litesvm";
import { Keypair, Transaction } from "@solana/web3.js";
import * as sdk from "../../dist/index.js";

const SO = fileURLToPath(new URL("../../../../target/deploy/solml_escrow.so", import.meta.url));
const step = (s) => console.log(`probe: ${s}`);
const svm = new LiteSVM();
const admin = Keypair.generate();
svm.airdrop(admin.publicKey, 100_000_000_000n);
const elf = readFileSync(SO);
const pid = sdk.PROGRAM_ID;
const pdata = sdk.programDataAddress(pid);
step("addProgramFromFile");
svm.addProgramFromFile(pid, SO);
const progData = Buffer.alloc(36);
progData.writeUInt32LE(2, 0);
pdata.toBuffer().copy(progData, 4);
const hdr = Buffer.alloc(45);
hdr.writeUInt32LE(3, 0);
hdr.writeUInt8(1, 12);
admin.publicKey.toBuffer().copy(hdr, 13);
const pd = Buffer.concat([hdr, elf]);
step(`setAccount programdata ${pd.length} bytes`);
svm.setAccount(pdata, { executable: false, owner: sdk.BPF_UPGRADEABLE_LOADER, lamports: svm.minimumBalanceForRentExemption(BigInt(pd.length)), data: pd, rentEpoch: 0 });
step("setAccount program");
svm.setAccount(pid, { executable: true, owner: sdk.BPF_UPGRADEABLE_LOADER, lamports: svm.minimumBalanceForRentExemption(36n), data: progData, rentEpoch: 0 });
const c = svm.getClock();
svm.setClock(new Clock(c.slot + 1n, c.epochStartTimestamp, c.epoch, c.leaderScheduleEpoch, 1_800_000_000n));
step("sendTransaction init_config");
const tx = new Transaction();
tx.recentBlockhash = svm.latestBlockhash();
tx.feePayer = admin.publicKey;
tx.add(sdk.initConfigIx({ admin: admin.publicKey, arbiter: admin.publicKey, treasury: admin.publicKey, protocolFeeBps: 50 }));
tx.sign(admin);
const res = svm.sendTransaction(tx);
step(`result ${res instanceof TransactionMetadata ? "ok" : res.err()}`);
step("logs");
const logs = res instanceof TransactionMetadata ? res.logs() : res.meta().logs();
step(`logs ${logs.length}`);
step("computeUnitsConsumed");
step(String(res instanceof TransactionMetadata ? res.computeUnitsConsumed() : res.meta().computeUnitsConsumed()));
step("expireBlockhash");
svm.expireBlockhash();
step("done");
